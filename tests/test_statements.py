"""PostgreSQL statements and functions beyond the core: target aliases, CREATE TABLE AS, TRUNCATE, FETCH FIRST,
DEFAULT VALUES, EXPLAIN and VACUUM options, read-only transactions, ordered-set aggregates, format() and
row values. The differential tests check the parts SQLite also has against SQLite."""

import pytest

from arcanum import Database
from arcanum.errors import ArcanumError, SqlError


@pytest.fixture
def db(tmp_path):
    with Database(tmp_path / "s.db", max_keys=4) as database:
        database.execute_script("""
            CREATE TABLE customers (id INTEGER PRIMARY KEY, name TEXT);
            CREATE TABLE orders (id INTEGER PRIMARY KEY, customer_id INTEGER REFERENCES customers (id), amount INTEGER);
            INSERT INTO customers VALUES (1, 'Ada'), (2, 'Lin');
            INSERT INTO orders VALUES (1, 1, 10), (2, 1, 20), (3, 2, 30), (4, 2, NULL);
        """)
        yield database


def rows(db, sql):
    return db.execute(sql).rows


def test_update_and_delete_targets_take_an_alias(db):
    assert rows(db, "UPDATE orders AS o SET amount = o.amount + 1 FROM customers c "
                    "WHERE c.id = o.customer_id AND c.name = 'Ada' RETURNING o.id, o.amount") == [(1, 11), (2, 21)]
    assert rows(db, "DELETE FROM orders o USING customers c WHERE c.id = o.customer_id AND c.name = 'Lin' "
                    "RETURNING o.id") == [(3,), (4,)]
    with pytest.raises(SqlError, match="missing FROM entry for table orders"):
        db.execute("UPDATE orders o SET amount = 0 WHERE orders.id = 1")  # the alias hides the name, as in PostgreSQL


def test_create_table_as_and_select_into(db):
    assert db.execute("CREATE TABLE big (order_id, total) AS SELECT id, amount * 2 FROM orders WHERE amount > 10"
                      ).status == "SELECT 2"
    assert rows(db, "SELECT * FROM big ORDER BY order_id") == [(2, 40), (3, 60)]
    db.execute("INSERT INTO big VALUES (9, 1)")  # a real table, with the query's column types
    with pytest.raises(ArcanumError):
        db.execute("INSERT INTO big VALUES ('x', 1)")
    db.execute("CREATE TABLE shape AS SELECT * FROM orders WITH NO DATA")
    assert rows(db, "SELECT count(*) FROM shape") == [(0,)]
    db.execute("SELECT name, NULL AS note INTO people FROM customers")
    assert rows(db, "SELECT * FROM people ORDER BY name") == [("Ada", None), ("Lin", None)]
    assert db.execute("CREATE TABLE IF NOT EXISTS people AS SELECT 1").status == "CREATE TABLE AS"
    with pytest.raises(SqlError, match="only allowed as a statement of its own"):
        db.execute("INSERT INTO big SELECT 1, 2 INTO elsewhere")
    with pytest.raises(SqlError, match="outermost SELECT"):
        db.execute("SELECT (SELECT 1 INTO inner_table)")


def test_create_table_as_survives_a_restart(tmp_path):
    with Database(tmp_path / "r.db") as db:
        db.execute("CREATE TABLE copy AS SELECT n, n * 1.5 AS half FROM generate_series(1, 3) AS n")
    with Database(tmp_path / "r.db") as db:
        assert rows(db, "SELECT * FROM copy ORDER BY n")[-1] == (3, 4.5)


def test_truncate_refuses_referenced_tables_unless_they_go_too(db):
    with pytest.raises(SqlError, match=r"foreign key .* on table orders references it"):
        db.execute("TRUNCATE customers")
    db.execute("BEGIN")
    assert db.execute("TRUNCATE TABLE customers, orders").status == "TRUNCATE TABLE"
    assert rows(db, "SELECT count(*) FROM orders") == [(0,)]
    db.execute("ROLLBACK")  # TRUNCATE is transactional here, as in PostgreSQL
    assert rows(db, "SELECT count(*) FROM orders") == [(4,)]
    db.execute("TRUNCATE customers CASCADE")
    assert rows(db, "SELECT (SELECT count(*) FROM customers), (SELECT count(*) FROM orders)") == [(0, 0)]
    with pytest.raises(SqlError, match="RESTART IDENTITY"):
        db.execute("TRUNCATE orders RESTART IDENTITY")


def test_fetch_first_and_offset_rows(db):
    assert rows(db, "SELECT id FROM orders ORDER BY id OFFSET 1 ROW FETCH FIRST 2 ROWS ONLY") == [(2,), (3,)]
    assert rows(db, "SELECT id FROM orders ORDER BY id FETCH NEXT ROW ONLY") == [(1,)]
    assert rows(db, "SELECT id FROM orders ORDER BY id OFFSET 2 LIMIT 1") == [(3,)]
    assert rows(db, "SELECT count(*) FROM (SELECT id FROM orders LIMIT ALL) t") == [(4,)]
    with pytest.raises(SqlError, match="given twice"):
        db.execute("SELECT id FROM orders LIMIT 1 FETCH FIRST 2 ROWS ONLY")


def test_insert_default_values(db):
    db.execute("CREATE TABLE events (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind TEXT DEFAULT 'tick')")
    assert rows(db, "INSERT INTO events DEFAULT VALUES RETURNING *") == [(1, "tick")]
    assert rows(db, "INSERT INTO events DEFAULT VALUES RETURNING id") == [(2,)]


def test_explain_and_vacuum_take_option_lists(db):
    lines = [r[0] for r in rows(db, "EXPLAIN (ANALYZE, COSTS false, FORMAT TEXT) SELECT * FROM orders")]
    assert "rows=4" in lines[0]
    assert "rows=" not in rows(db, "EXPLAIN (ANALYZE off) SELECT * FROM orders")[0][0]
    assert rows(db, "EXPLAIN (SELECT 1)")  # a parenthesized query, not options
    with pytest.raises(SqlError, match="unrecognized EXPLAIN option"):
        db.execute("EXPLAIN (FASTER) SELECT 1")
    with pytest.raises(SqlError, match="formats other than TEXT"):
        db.execute("EXPLAIN (FORMAT JSON) SELECT 1")
    assert db.catalog.tables["orders"].stats is None
    db.execute("VACUUM (FULL, ANALYZE) orders")
    assert db.catalog.tables["orders"].stats is not None
    db.execute("VACUUM ANALYZE")
    assert db.catalog.tables["customers"].stats is not None


def test_read_only_transactions_refuse_changes(db):
    db.execute("BEGIN READ ONLY")
    assert rows(db, "SELECT count(*) FROM orders") == [(4,)]
    for sql in ("INSERT INTO orders VALUES (9, 1, 1)", "TRUNCATE orders", "CREATE TABLE t (a INTEGER)"):
        with pytest.raises(SqlError, match="in a read-only transaction"):
            db.execute(sql)
    db.execute("COMMIT")
    db.execute("START TRANSACTION ISOLATION LEVEL REPEATABLE READ, READ WRITE, NOT DEFERRABLE")
    db.execute("INSERT INTO orders VALUES (9, 1, 1)")
    db.execute("COMMIT")
    db.execute("INSERT INTO orders VALUES (10, 1, 1)")  # read-only ends with its transaction


def test_ordered_set_aggregates(db):
    db.execute("INSERT INTO orders VALUES (5, 1, 20), (6, 2, 40)")
    assert rows(db, """
        SELECT customer_id, percentile_cont(0.5) WITHIN GROUP (ORDER BY amount),
               percentile_disc(0.5) WITHIN GROUP (ORDER BY amount),
               mode() WITHIN GROUP (ORDER BY amount),
               percentile_cont(0.25) WITHIN GROUP (ORDER BY amount DESC)
        FROM orders GROUP BY customer_id ORDER BY customer_id""") == [(1, 20.0, 20, 20, 20.0), (2, 35.0, 30, 30, 37.5)]
    assert rows(db, "SELECT percentile_cont(0.5) WITHIN GROUP (ORDER BY amount) FROM orders WHERE false") == [(None,)]
    plan = rows(db, "EXPLAIN SELECT mode() WITHIN GROUP (ORDER BY amount) FROM orders")[0][0]
    assert "mode() WITHIN GROUP (ORDER BY amount)" in plan
    for sql, message in [
        ("SELECT percentile_cont(1.5) WITHIN GROUP (ORDER BY amount) FROM orders", "not between 0 and 1"),
        ("SELECT mode(amount) FROM orders", "needs WITHIN GROUP"),
        ("SELECT sum(amount) WITHIN GROUP (ORDER BY id) FROM orders", "not an ordered-set aggregate"),
        ("SELECT percentile_cont(amount) WITHIN GROUP (ORDER BY id) FROM orders", "same for the whole group"),
    ]:
        with pytest.raises(ArcanumError, match=message):
            db.execute(sql)


def test_format_md5_and_quoting(db):
    assert rows(db, "SELECT format('%s has %s orders; %I.%I = %L, %L, %% %1$s |%-4s|%4s|', "
                    "'Ada', 2, 'My Table', 'id', 'it''s', NULL)") == [
        ("Ada has 2 orders; \"My Table\".id = 'it''s', NULL, % Ada |2   |My Table|",)]  # %1$s moves on to 2
    assert rows(db, "SELECT format(NULL, 1), format('%s', NULL), md5('abc'), quote_ident('select'), "
                    "quote_ident('plain'), quote_literal('a\\b')") == [
        (None, "", "900150983cd24fb0d6963f7d28e17f72", '"select"', "plain", "E'a\\\\b'")]
    for sql in ("SELECT format('%s')", "SELECT format('%x', 1)", "SELECT format('%I', NULL)"):
        with pytest.raises(ArcanumError, match="format"):
            db.execute(sql)


def test_like_escapes_with_backslash_or_the_escape_given(db):
    assert rows(db, "SELECT 'a_b' LIKE 'a\\_b', 'axb' LIKE 'a\\_b', '50%' LIKE '50!%' ESCAPE '!', "
                    "'5x' LIKE '5!%' ESCAPE '!', 'a\\b' LIKE 'a\\b' ESCAPE '', 'AB' ILIKE 'a%' ESCAPE ''") == [
        (True, False, True, False, True, True)]
    with pytest.raises(ArcanumError, match="escape character"):
        db.execute("SELECT 'a' LIKE 'a\\'")


def test_window_functions_for_buckets_and_distribution(db):
    assert rows(db, "SELECT id, ntile(3) OVER (ORDER BY id), nth_value(id, 2) OVER (ORDER BY id) FROM orders") == [
        (1, 1, None), (2, 1, 2), (3, 2, 2), (4, 3, 2)]
    with pytest.raises(ArcanumError, match="ntile must be greater than zero"):
        db.execute("SELECT ntile(0) OVER () FROM orders")


def test_named_windows_build_on_each_other(db):
    assert rows(db, "SELECT id, row_number() OVER w2 FROM orders "
                    "WINDOW w1 AS (PARTITION BY customer_id), w2 AS (w1 ORDER BY id DESC) ORDER BY id") == [
        (1, 2), (2, 1), (3, 2), (4, 1)]
    for sql, message in [
        ("SELECT sum(amount) OVER nope FROM orders", "window nope does not exist"),
        ("SELECT sum(amount) OVER (w PARTITION BY id) FROM orders WINDOW w AS (PARTITION BY customer_id)",
         "cannot override the PARTITION BY"),
        ("SELECT 1 FROM orders WINDOW w AS (), w AS ()", "already defined"),
    ]:
        with pytest.raises(SqlError, match=message):
            db.execute(sql)


def test_row_values_compare_field_by_field(db):
    assert rows(db, "SELECT id FROM orders WHERE (customer_id, amount) = (1, 20)") == [(2,)]
    assert rows(db, "SELECT id FROM orders WHERE (customer_id, amount) IN ((1, 10), (2, 30)) ORDER BY id") == [
        (1,), (3,)]
    assert rows(db, "SELECT id FROM orders WHERE ROW(customer_id, amount) > ROW(1, 10) ORDER BY id") == [
        (2,), (3,), (4,)]  # the first fields decide order 4: its NULL amount is never compared
    assert rows(db, "SELECT id FROM orders WHERE (customer_id, amount) > (2, 10) ORDER BY id") == [(3,)]
    for sql, message in [
        ("SELECT (1, 2)", "row values only in comparisons"),
        ("SELECT 1 WHERE (1, 2) = (1, 2, 3)", "same number of fields"),
        ("SELECT 1 FROM orders WHERE (id, amount) IN (SELECT id, amount FROM orders)", "IN \\(subquery\\)"),
    ]:
        with pytest.raises(SqlError, match=message):
            db.execute(sql)
